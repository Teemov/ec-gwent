"""Regenerates docs/cards.md from the card JSON files. Run from the repo root: python3 tools/cards_md.py"""
import json
order = ['valarians', 'illagers', 'monsters', 'orcs', 'islanders', 'neutral', 'special']
perks = {'draw_on_round_win': 'draws a card after each round it wins', 'win_draws': 'wins any round that ends in a draw',
         'keep_random_unit': 'keeps one random unit on the board after each round', 'choose_first_player': 'chooses who goes first',
         'revive_two_in_round_three': 'two random units return from the graveyard at the start of round 3', None: ''}
AB = {'bond': 'Tight Bond', 'muster': 'Muster', 'spy': 'Spy', 'medic': 'Medic', 'morale': 'Morale', 'horn': 'Horn',
      'scorch': 'Scorch (whole board)', 'scorch_close': 'Scorch – Close', 'scorch_ranged': 'Scorch – Ranged',
      'scorch_siege': 'Scorch – Siege', 'avenger': 'Avenger', 'berserker': 'Berserker', 'mardroeme': 'Mardroeme',
      'decoy': 'Decoy', 'frost': 'Frost (Close)', 'fog': 'Fog (Ranged)', 'rain': 'Rain (Siege)',
      'storm': 'Storm (Ranged + Siege)', 'clear': 'Clear weather'}
out = ['# EC Gwent card list', '', 'Generated by `tools/cards_md.py` from `src/main/resources/data/ec_gwent/gwent_cards/*.json`. '
       'Every card keeps the strength, row, ability and copy count of its Witcher 3 original.', '']
for f in order:
    d = json.load(open(f'src/main/resources/data/ec_gwent/gwent_cards/{f}.json'))
    cards = d['cards']
    n = sum(c['count'] for c in cards if c['type'] != 'leader')
    out += [f"## {d['name']} ({n} cards)", '']
    if d['perk']:
        out += [f"Faction perk: {perks[d['perk']]}.", '']
    L = [c for c in cards if c['type'] == 'leader']
    if L:
        out += ['| Leader | Witcher 3 | Ability |', '|---|---|---|'] + [f"| {c['name']} | {c['w3']} | `{c['ability']}` |" for c in L] + ['']
    out += ['| Card | Witcher 3 | Row | Str | Ability | Copies | Mob |', '|---|---|---|---|---|---|---|']
    for c in cards:
        if c['type'] == 'leader':
            continue
        ab = ', '.join((['Hero'] if c['type'] == 'hero' else []) + [AB.get(a, a) for a in c.get('abilities', [])])
        extra = []
        if c.get('muster'): extra.append(f"group `{c['muster']}`")
        if c.get('avenger'): extra.append(f"becomes {c['avenger']}")
        if c.get('transforms'): extra.append(f"becomes {c['transforms']}")
        if c.get('summoned_only'): extra.append('only summoned')
        if extra: ab += ' (' + '; '.join(extra) + ')'
        mob = f"`{c['entity']}`" + (f" holding `{c['item']}`" if c.get('item') else '')
        st = c.get('strength')
        out.append(f"| {c['name']} | {c['w3']} | {c.get('row') or '–'} | {st if st is not None else '–'} | {ab} | {c['count']} | {mob} |")
    out.append('')
open('docs/cards.md', 'w').write('\n'.join(out))
print('docs/cards.md:', len(out), 'lines')
